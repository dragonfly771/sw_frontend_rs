#!/bin/bash
#
# Builds the firmware image for exactly one display variant:
#
#   ./make_variant.sh small    round series display   -> larus_frontend_v2_v<version>.bin/.elf
#   ./make_variant.sh large    large 2.76" display    -> larus_frontend_v2_large_v<version>.bin/.elf
#
# The variant decides the hardware version in the code and in the image header
# (small 1.3.2.0, large 1.3.3.0). A device only installs an image from the SD card
# whose hardware version matches its own, so the wrong file is ignored. pack.py checks
# that the code and the header agree before it writes anything.
#
# The software version is taken from src/utils/version.rs (SW_VERSION).

set -e
cd "$(dirname "$0")"

case "$1" in
    small)
        FEATURES=""
        HW_VERSION="1.3.2.0"
        PREFIX="larus_frontend_v2"
        ;;
    large)
        FEATURES="--features display_large"
        HW_VERSION="1.3.3.0"
        PREFIX="larus_frontend_v2_large"
        ;;
    *)
        echo "Usage: ./make_variant.sh small|large"
        echo "  small  round series display (hardware 1.3.2.0)"
        echo "  large  large 2.76\" display  (hardware 1.3.3.0)"
        exit 1
        ;;
esac

SW_VERSION=$(sed -n 's/.*version: \[\([0-9]*\), *\([0-9]*\), *\([0-9]*\), *\([0-9]*\)\].*/\1.\2.\3.\4/p' src/utils/version.rs | head -1)
if [ -z "$SW_VERSION" ]; then
    echo "SW_VERSION not found in src/utils/version.rs"
    exit 1
fi
SW_VERSION_FN=$(echo "$SW_VERSION" | tr '.' '-')

# python with pyelftools and toml
PY=""
for candidate in ../../.venv/bin/python "$HOME/.stefly-venv/bin/python" python3; do
    if command -v "$candidate" >/dev/null 2>&1 && "$candidate" -c "import elftools, toml" 2>/dev/null; then
        PY="$candidate"
        break
    fi
done
if [ -z "$PY" ]; then
    echo "No python with pyelftools and toml found: pip3 install pyelftools toml"
    exit 1
fi

echo "Variant:     $1"
echo "Hardware:    $HW_VERSION"
echo "Software:    $SW_VERSION"
echo "Image:       ${PREFIX}_v${SW_VERSION_FN}.bin"
echo

cat > pack.toml <<TOML
# generated by make_variant.sh $1 - do not edit
[app]
elf = "target/thumbv7em-none-eabihf/release/vario"
addr_start = 0x0800_0000
addr_max = 0x0807_ffff

[copy]
elf = "scripts/copy_stm32h743_1m.elf"
addr_start = 0x0810_1000
addr_max = 0x0810_5fff

[image]
elf = "${PREFIX}_v${SW_VERSION_FN}.elf"
name = "${PREFIX}_v${SW_VERSION_FN}.bin"
addr_storage = 0x0810_0000
hw_version = "${HW_VERSION}"
sw_version = "${SW_VERSION}"
TOML

DEFMT_LOG=off cargo build --release $FEATURES
"$PY" scripts/pack.py

echo
echo "finished: ${PREFIX}_v${SW_VERSION_FN}.bin ($1)"
